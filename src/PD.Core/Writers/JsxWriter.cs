using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using PD.Core.Config;

namespace PD.Core.Writers;

/// <summary>Master ExtendScript: the runtime library plus every drawing embedded as a JS object literal (PRD 6).</summary>
public static class JsxWriter
{
    public static readonly JsonSerializerOptions Json = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        Converters = { new JsonStringEnumConverter() },
    };

    public static string Runtime()
    {
        using var s = typeof(JsxWriter).Assembly.GetManifestResourceStream("PD.Core.Illustrator.runtime.jsx")
            ?? throw new FileNotFoundException("runtime.jsx not embedded");
        using var r = new StreamReader(s);
        return r.ReadToEnd();
    }

    public static string Write(IEnumerable<PD.Core.Drawing.Drawing> drawings, string outDir)
    {
        // JSON is a JS literal except for U+2028/2029; ExtendScript (ES3) has no JSON.parse, so embed directly.
        var data = JsonSerializer.Serialize(drawings, Json).Replace("\u2028", "\\u2028").Replace("\u2029", "\\u2029");
        var opts = JsonSerializer.Serialize(new { outDir = outDir.Replace('\\', '/') }, Json);
        var sb = new StringBuilder();
        sb.AppendLine("#target illustrator");
        sb.AppendLine("// Generated by Program Diagram. Run from Illustrator: File > Scripts > Other Script…");
        sb.AppendLine(Runtime());
        sb.AppendLine($"PD.run({data}, {opts});");
        return sb.ToString();
    }
}
